// Concatenation
let firstName = "Kamal"
let lastName = "Perera"

let fullName = firstName + " " + lastName
print(fullName)
// Output: Kamal Perera

// String Interpolation
let personName = "Kamal"
let age = 22

print("My name is \(personName) and I am \(age) years old.")
// Output: My name is Kamal and I am 22 years old.

